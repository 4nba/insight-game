import assert from 'node:assert/strict';
import worker from '../worker.js';
import { env } from './worker_fixture.mjs';

const request = (path, options) => worker.fetch(new Request('https://test.local' + path, options), env);
const post = state => ({ method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(state) });
assert.equal((await worker.fetch(new Request('https://test.local/api/health'), {})).status, 503);
assert.equal((await request('/api/health')).status, 200);
assert.equal((await request('/api/room/missing')).status, 404);
assert.equal((await request('/api/sessions')).headers.get('cache-control'), 'no-store');
assert.equal((await request('/api/room/invalid.id', post({players:[]}))).status, 404);
assert.equal((await request('/api/room/test', post({players:[null]}))).status, 400);
assert.equal((await request('/api/room/test', post({players:Array(51).fill({})}))).status, 400);
assert.equal((await request('/api/room/test', {method:'POST',body:'{broken'})).status, 400);
assert.equal((await request('/api/room/test', {method:'POST',body:'x'.repeat(524289)})).status, 413);
const state = {players:[{name:'Test',notes:{insights:'Personal note'}}],sessionTitle:'First game'};
assert.equal((await request('/api/room/first', post(state))).status, 200);
assert.deepEqual((await (await request('/api/room/first')).json()).players, state.players);
const duplicate = post(state);
duplicate.headers['If-None-Match'] = '*';
assert.equal((await request('/api/room/first', duplicate)).status, 409);
assert.equal((await request('/api/room/second', post({...state,sessionTitle:'Second game'}))).status, 200);
await request('/api/room/first', post({...state,sessionTitle:'Renamed'}));
const list = await (await request('/api/sessions')).json();
assert.equal(list.sessions.length, 2);
assert.equal(list.sessions.find(s => s.id === 'first').title, 'Renamed');
assert.equal(JSON.stringify(list).includes('Personal note'), false);
assert.equal((await request('/api/room/first', {method:'DELETE'})).status, 405);
console.log('WORKER API OK: real SQLite schema, save/load/list, independent sessions, create-only, validation, no-store');
